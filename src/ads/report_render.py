def render_markdown(ctx: dict[str, Any]) -> str:
    """Render report.md from the context dict."""
    text = _env.from_string(REPORT_MD_TEMPLATE).render(**ctx)
    return re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"


# ---------------------------------------------------------------------------------------
# A small markdown -> HTML converter for the constructs this report uses
# (headings, paragraphs, lists, tables, images, blockquotes, bold/italic/code/links).
# ---------------------------------------------------------------------------------------

_IMG_RE = re.compile(r"^!\[(?P<alt>[^\]]*)\]\((?P<src>[^)]+)\)$")


def _inline(text: str) -> str:
    out = html.escape(text, quote=False)
    codes: list[str] = []

    def keep_code(m: re.Match[str]) -> str:
        codes.append(m.group(1))
        return f"\x00{len(codes) - 1}\x00"

    out = re.sub(r"`([^`]+)`", keep_code, out)
    out = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"(?<![*\w])\*([^*\n]+)\*(?![*\w])", r"<em>\1</em>", out)
    out = re.sub(r"(?<![\w])_([^_\n]+)_(?![\w])", r"<em>\1</em>", out)
    out = re.sub(r"\x00(\d+)\x00", lambda m: f"<code>{codes[int(m.group(1))]}</code>", out)
    return out


def _split_row(line: str) -> list[str]:
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|"):
        body = body[:-1]
    cells, cur, esc = [], [], False
    for ch in body:
        if esc:
            cur.append(ch)
            esc = False
        elif ch == "\\":
            esc = True
        elif ch == "|":
            cells.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    cells.append("".join(cur).strip())
    return cells


def _table_html(lines: list[str]) -> str:
    header = _split_row(lines[0])
    align = []
    if len(lines) > 1 and set(lines[1].replace("|", "").replace(":", "").replace("-", "").strip()) == set():
        align = ["num" if c.strip().endswith(":") and not c.strip().startswith(":") else "" for c in _split_row(lines[1])]
        rows = lines[2:]
    else:
        rows = lines[1:]

    def cls(i: int) -> str:
        return f' class="{align[i]}"' if i < len(align) and align[i] else ""

    parts = ["<table>", "<thead><tr>" + "".join(f"<th{cls(i)}>{_inline(h)}</th>" for i, h in enumerate(header)) + "</tr></thead>", "<tbody>"]
    for r in rows:
        cells = _split_row(r)
        parts.append("<tr>" + "".join(f"<td{cls(i)}>{_inline(c)}</td>" for i, c in enumerate(cells)) + "</tr>")
    parts.append("</tbody></table>")
    return "\n".join(parts)


def markdown_to_html(md: str) -> str:
    """Convert the report's markdown to HTML (body only)."""
    lines = md.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s or s.startswith("<!--"):
            i += 1
            continue
        if s.startswith("#"):
            level = len(s) - len(s.lstrip("#"))
            out.append(f"<h{level}>{_inline(s[level:].strip())}</h{level}>")
            i += 1
        elif s.startswith("|"):
            block = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                block.append(lines[i])
                i += 1
            out.append(_table_html(block))
        elif _IMG_RE.match(s):
            m = _IMG_RE.match(s)
            assert m is not None
            out.append(
                f'<figure><img src="{html.escape(m.group("src"))}" alt="{html.escape(m.group("alt"))}" loading="lazy"></figure>'
            )
            i += 1
        elif s.startswith("- "):
            items = []
            while i < len(lines) and lines[i].strip().startswith("- "):
                items.append(f"<li>{_inline(lines[i].strip()[2:])}</li>")
                i += 1
            out.append("<ul>\n" + "\n".join(items) + "\n</ul>")
        elif s.startswith(">"):
            quote = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                quote.append(lines[i].strip()[1:].strip())
                i += 1
            out.append(f"<blockquote>{_inline(' '.join(quote))}</blockquote>")
        else:
            para = []
            while i < len(lines) and lines[i].strip() and not lines[i].strip().startswith(("#", "|", "- ", ">", "![", "<!--")):
                para.append(lines[i].strip())
                i += 1
            text = " ".join(para)
            cls = ' class="caption"' if text.startswith("*Figure ") else ""
            out.append(f"<p{cls}>{_inline(text)}</p>")
    return "\n".join(out)


def render_html(md: str, title: str) -> str:
    """Wrap the converted markdown in the HTML page template."""
    return _env.from_string(HTML_TEMPLATE).render(title=html.escape(title), body=markdown_to_html(md))


