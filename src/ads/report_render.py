def _n(v: Any) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        if v.is_integer():
            return f"{int(v):,}"
        return f"{v:,.3f}".rstrip("0").rstrip(".")
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _cleaning_section(log: list[dict[str, Any]], summary: dict[str, Any], dropped: list[dict[str, Any]], outliers: dict[str, Any], rows_raw: int, rows_cons: int, rows_imp: int) -> dict[str, Any]:
    by_step: dict[str, dict[str, int]] = {}
    for e in log:
        st = by_step.setdefault(e["step"], {"entries": 0, "cells": 0, "rows_removed": 0})
        st["entries"] += 1
        st["cells"] += int(e.get("n_cells_affected", 0))
        if e["step"] in {"handle_duplicates", "structural_drops"}:
            st["rows_removed"] += max(0, int(e.get("rows_before", 0)) - int(e.get("rows_after", 0)))
    steps = [{"step": k, "entries": _n(v["entries"]), "cells": _n(v["cells"]), "rows_removed": _n(v["rows_removed"])} for k, v in by_step.items()]

    requirements = []
    for label, step_set in CLEANING_GROUPS:
        actions: dict[str, list[int]] = {}
        for e in log:
            if e["step"] in step_set:
                a = actions.setdefault(e["action"], [0, 0])
                a[0] += int(e.get("n_cells_affected", 0))
                a[1] += int(e.get("n_rows_affected", 0))
        if actions:
            parts = []
            row_based = bool(step_set & {"handle_duplicates", "structural_drops"})
            for act, (cells, rows) in sorted(actions.items()):
                nice = act.replace("_", " ")
                if row_based and rows:
                    parts.append(f"{nice}: {_n(rows)} rows")
                elif cells:
                    parts.append(f"{nice}: {_n(cells)} cells")
                elif rows:
                    parts.append(f"{nice}: {_n(rows)} rows")
                else:
                    parts.append(nice)
            text = "✔ " + "; ".join(parts)
        else:
            text = "✔ checked; nothing to change"
        if label == "Missing values":
            text += ". Conservative output keeps NaN; imputed output fills gaps and adds `__was_missing` flags"
        if label == "Outliers":
            text += f". {len(outliers)} column(s) flagged; values are kept in the conservative output"
        requirements.append((label, _cell(text)))

    total_cells = summary.get("total_cells_affected", sum(int(e.get("n_cells_affected", 0)) for e in log))
    sentence = (
        f"{len(by_step)} cleaning steps made {len(log)} logged changes touching {_n(int(total_cells))} cells. "
        f"Rows: {_n(rows_raw)} in the raw file → {_n(rows_cons)} in the conservative output → {_n(rows_imp)} in the imputed output."
    )
    drop_rows = [
        {
            "name": d.get("name"),
            "where": {"both": "both outputs", "imputed_only": "imputed output only", "marked_excluded": "kept, marked excluded"}.get(d.get("output_target"), d.get("output_target")),
            "reason": _cell(d.get("reason", "")),
        }
        for d in dropped
    ]
    out_rows = []
    for col, o in sorted(outliers.items()):
        lo, hi = o.get("iqr_1_5_lower"), o.get("iqr_1_5_upper")
        out_rows.append(
            {
                "column": col,
                "n_flagged": _n(o.get("n_flagged")),
                "pct": f"{100 * float(o.get('pct_flagged') or 0):.2f}%",
                "n_extreme": _n(o.get("n_extreme")),
                "bounds": f"{_n(lo)} to {_n(hi)}" if lo is not None and hi is not None else "",
                "action": o.get("action_taken", "flag"),
            }
        )
    return {"summary_sentence": sentence, "requirements": requirements, "steps": steps, "dropped": drop_rows, "outliers": out_rows}


def build_context(
    *,
    name: str,
    profile: dict[str, Any],
    log: list[dict[str, Any]],
    cleaning_summary: dict[str, Any],
    dropped_columns: list[dict[str, Any]],
    outlier_report: dict[str, Any],
    shapes: dict[str, tuple[int, int]],
    figures: list[dict[str, Any]],
    tables: dict[str, str],
    headline: dict[str, Any],
    scaling: dict[str, Any],
    insights: list[dict[str, Any]],
    manual_block: str,
    output_files: list[str],
) -> dict[str, Any]:
    """Assemble the template context from plain dicts (all pydantic objects already dumped)."""
    rows_raw, cols_raw = shapes["raw"]
    rows_c, cols_c = shapes["conservative"]
    rows_i, cols_i = shapes["imputed"]
    mms = profile.get("missing_matrix_summary") or {}
    overview = [
        ("Source file", f"`{profile.get('source_file', '')}`"),
        ("SHA-256", f"`{profile.get('sha256', '')}`"),
        ("Raw shape", f"{_n(rows_raw)} rows × {_n(cols_raw)} columns"),
        ("Cleaned shape (conservative, primary)", f"{_n(rows_c)} rows × {_n(cols_c)} columns"),
        ("Cleaned shape (imputed, secondary)", f"{_n(rows_i)} rows × {_n(cols_i)} columns"),
        ("Exact duplicate rows in raw file", _n(profile.get("n_duplicate_rows", 0))),
        ("Missing cells in raw file (incl. placeholder text)", f"{_n(mms.get('total_missing_cells', 0))} ({100 * float(mms.get('pct_missing_cells', 0) or 0):.2f}%)"),
        ("Memory (raw)", f"{profile.get('memory_mb', 0)} MB"),
    ]
    tgt = headline.get("target") or {}
    if tgt.get("name"):
        overview.append(("Target column", f"`{tgt['name']}` ({tgt.get('kind', '')})"))

    columns = [
        {
            "name": c.get("name"),
            "raw_dtype": c.get("raw_dtype"),
            "semantic_type": c.get("semantic_type"),
            "pct_missing": f"{100 * float(c.get('pct_missing') or 0):.1f}%",
            "n_unique": _n(c.get("n_unique")),
            "reason": _cell(c.get("semantic_type_reason", "")),
        }
        for c in profile.get("columns", [])
    ]

    sections = []
    fig_no = 0
    by_section: dict[str, list[dict[str, Any]]] = {}
    for f in figures:
        by_section.setdefault(f.get("section", "other"), []).append(f)
    intros = {
        "missingness": (headline.get("missingness") or {}).get("concentration_note", ""),
        "relationships": "All coefficients here describe the data; none of them is a test result. Spearman rho and Pearson r range from -1 to +1; eta² and Cramér's V range from 0 (no association) to 1.",
        "numeric": "Red dots in box plots are values beyond 1.5×IQR; they are flagged but kept in the conservative cleaned data.",
    }
    for key, title in SECTION_TITLES:
        figs = []
        for f in by_section.get(key, []):
            fig_no += 1
            figs.append({"number": fig_no, "title": f["title"].rstrip("."), "caption": f["caption"], "rel_path": f.get("rel_path") or f"figures/{f['filename']}"})
        tbls = [{"heading": h, "body": tables[k].strip()} for k, h in SECTION_TABLES.get(key, []) if k in tables]
        if not figs and not tbls:
            continue
        sections.append({"title": title, "intro": intros.get(key, ""), "figures": figs, "tables": tbls})

    notes = list(headline.get("notes", []))
    for err in headline.get("eda_errors", []):
        notes.append(f"EDA section '{err['section']}' could not be drawn: {err['error']}")

    top_ins = [
        {
            "severity": i["severity"],
            "category_title": CATEGORY_TITLES.get(i["category"], i["category"]),
            "statement": i["statement"] + (f" ([figure]({i['figure_ref']}))" if i.get("figure_ref") else ""),
        }
        for i in insights
        if i["severity"] in {"high", "medium"}
    ]
    manual_lines = [ln for ln in manual_block.splitlines() if not ln.strip().startswith("<!--")]
    manual_text = "\n".join(manual_lines).strip() or "_Not written yet._"

    sc_rows = [
        {"column": r["column"], "skew": f"{float(r.get('skewness') or 0):+.2f}", "transform": r.get("recommended_transform", "none"), "reason": _cell(r.get("reason", ""))}
        for r in scaling.get("columns", [])
    ]
    disparity = ""
    if scaling.get("scale_disparity_ratio") is not None:
        disparity = (
            f"Scale disparity across numeric columns (largest std ÷ smallest std): {_n(round(float(scaling['scale_disparity_ratio']), 2))}. "
            + ("Z-score standardization is recommended only for scale-sensitive methods." if scaling.get("recommend_zscore_for_scale_sensitive") else "No standardization is needed for the planned rank-based tests.")
        )

    return {
        "name": name,
        "overview": overview,
        "warnings": [_cell(w) for w in profile.get("warnings", [])],
        "columns": columns,
        "cleaning": _cleaning_section(log, cleaning_summary, dropped_columns, outlier_report, rows_raw, rows_c, rows_i),
        "eda_notes": notes,
        "eda_sections": sections,
        "insights": top_ins,
        "n_insights_total": len(insights),
        "manual_text": manual_text,
        "scaling": {
            "rows": sc_rows,
            "disparity": disparity,
            "decision": (scaling.get("decision_paragraph") or "No scaling decision was recorded.").replace("\n", " "),
            "scaled_csv": scaling.get("scaled_csv_path"),
        },
        "outputs": output_files,
    }
